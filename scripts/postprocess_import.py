"""Stage B of the upstream import: raw FontForge UFO -> clean source UFO.

    python scripts/postprocess_import.py build/import build/reference/X.otf OUT.ufo

* renames the family to Myia Didot and resets the name/version metadata;
* renames legacy afii* glyph names to uniXXXX everywhere (glyphs, components,
  features, kerning groups);
* moves class kerning from the FontForge feature file into groups.plist +
  kerning.plist, GDEF classes into public.openTypeCategories and ligature
  carets into caret_N anchors, so ufo2ft regenerates kern/mark/mkmk/GDEF;
* keeps only the hand-written GSUB part of the feature file, plus the Greek
  "accent before capital" positioning that FontForge stored in a required
  (' RQD') feature, which is moved into kern;
* copies vertical metrics and glyph order from the FontForge-built
  reference binary, so the round-trip comparison is like for like.
"""

import json
import re
import sys
from pathlib import Path

import ufoLib2
from fontTools import agl
from fontTools.ttLib import TTFont

FAMILY = "Myia Didot"
PS_FAMILY = "MyiaDidot"
VERSION = (0, 100)
COPYRIGHT = (
    "Copyright 2007-2011 Alexey Kryukov (Theano Didot). "
    "Copyright 2026 The Myia Didot Project Authors."
)
LICENSE = (
    "This Font Software is licensed under the SIL Open Font License, "
    "Version 1.1. This license is available with a FAQ at: "
    "https://openfontlicense.org"
)
LICENSE_URL = "https://openfontlicense.org"

TOKEN = re.compile(r"\\([A-Za-z0-9_.\-]+)")


def build_rename_map(ufo):
    rename = {}
    for g in ufo:
        if not g.name.startswith("afii"):
            continue
        base, dot, suffix = g.name.partition(".")
        uv = g.unicode if not dot else None
        if uv is None:
            uv = agl.AGL2UV.get(base)
        if uv is None:
            raise SystemExit(f"cannot derive a name for {g.name}")
        new = (f"uni{uv:04X}" if uv <= 0xFFFF else f"u{uv:05X}") + dot + suffix
        rename[g.name] = new
    clashes = set(rename.values()) & set(ufo.keys())
    if clashes:
        raise SystemExit(f"rename clashes with existing glyphs: {sorted(clashes)}")
    return rename


def rename_glyphs(ufo, rename):
    for old, new in rename.items():
        ufo.renameGlyph(old, new)
    for g in ufo:
        for c in g.components:
            c.baseGlyph = rename.get(c.baseGlyph, c.baseGlyph)


def fea_rename(text, rename):
    return TOKEN.sub(lambda m: "\\" + rename.get(m.group(1), m.group(1)), text)


def split_fea(text):
    """Return (header+GSUB, Greek caps GPOS lookups, GDEF class block)."""
    gsub_start = text.index("# GSUB")
    gpos_start = text.index("# GPOS")
    header = text[:gsub_start]
    gsub = text[gsub_start:gpos_start]
    # FontForge exports the Cyrillic breve context (nested lookup applied at
    # position 1) as a substitution of the whole sequence, deleting the base.
    gsub = gsub.replace(
        "sub @cc2_match_1' @cc2_match_2'  by [\\brevecmb.cyrl ] ;",
        "sub @cc2_match_1 @cc2_match_2' by \\brevecmb.cyrl;",
    )
    # The feature file spec forbids script/language statements in aalt.
    gsub = re.sub(
        r"feature aalt \{.*?\} aalt;",
        "feature aalt {\n    lookup aaltAccessAllAlternates;\n} aalt;",
        gsub,
        flags=re.DOTALL,
    )
    gpos = text[gpos_start:]

    # The standalone single-pos lookups plus the contextual driver lookup
    # (everything before FontForge's own mark lookup).
    caps = gpos[: gpos.index("lookup markMarkPositioning")]
    caps = caps.replace("# GPOS", "").strip()
    caps = caps.replace(
        "RQDGreekCapsafterAccentsPositioning", "GreekCapsAccentPositioning"
    )

    gdef_classes = {}
    for cls in ("Simple", "Ligature", "Mark"):
        m = re.search(rf"@GDEF_{cls} = \[(.*?)\];", gpos, re.DOTALL)
        gdef_classes[cls] = TOKEN.findall(m.group(1)) if m else []
    return header + gsub, caps, gdef_classes


def write_features(ufo, gsub, caps):
    kern = (
        "feature kern {\n"
        "    # Upstream Theano used a FontForge 'required' feature for this;\n"
        "    # it shifts Greek capitals right of a preceding spacing accent\n"
        "    # and must run before the generated kerning.\n"
        "    lookup GreekCapsAccentPositioning;\n"
        "    # Automatic Code\n"
        "} kern;\n"
    )
    ufo.features.text = (
        "# Myia Didot OpenType features (GSUB + Greek capital accent spacing).\n"
        "# kern pairs, mark, mkmk and GDEF are generated by ufo2ft from\n"
        "# kerning.plist, anchors and public.openTypeCategories.\n\n"
        + gsub.strip()
        + "\n\n# GPOS\n\n"
        + caps
        + "\n\n"
        + kern
    )


def import_kerning(ufo, subtables, rename):
    """Merge FontForge's per-script class-kerning subtables into UFO kerning.

    A class-pair subtable whose coverage holds the left glyph ends the lookup,
    so a pair is resolved by the first subtable listing its left glyph; later
    left-side memberships are dead and are dropped. Right-side glyphs may sit
    in classes of several subtables; they are regrouped by their membership
    signature (class index in every subtable), which keeps every pair value.
    """

    def r(n):
        return rename.get(n, n)

    def nonzero(st, i, j):
        return st["offsets"][i * len(st["second"]) + j]

    for st in subtables:
        for i in range(len(st["first"])):
            for j in range(len(st["second"])):
                if (i == 0 or j == 0) and nonzero(st, i, j):
                    raise SystemExit(f"kerning value on class 0 in {st['subtable']}")

    kern1 = {}
    for s, st in enumerate(subtables):
        for i, members in enumerate(st["first"]):
            members = [r(m) for m in members if m and r(m) not in kern1]
            if members:
                group = "public.kern1." + members[0]
                ufo.groups[group] = members
                for m in members:
                    kern1[m] = (s, i, group)

    signature = {}
    for s, st in enumerate(subtables):
        for j, members in enumerate(st["second"]):
            for m in members:
                if m:
                    signature.setdefault(r(m), {})[s] = j
    by_sig = {}
    for glyph, sig in signature.items():
        by_sig.setdefault(tuple(sorted(sig.items())), []).append(glyph)
    order = {n: k for k, n in enumerate(ufo.keys())}
    kern2 = []
    for sig, members in by_sig.items():
        members.sort(key=order.__getitem__)
        group = "public.kern2." + members[0]
        ufo.groups[group] = members
        kern2.append((dict(sig), group))

    first_groups = {(s, i): g for s, i, g in kern1.values()}
    for (s, i), g1 in first_groups.items():
        for sig, g2 in kern2:
            if s in sig and (value := nonzero(subtables[s], i, sig[s])):
                ufo.kerning[(g1, g2)] = value


def import_gdef(ufo, gdef_classes, carets, rename):
    cats = {}
    for cls, cat in (("Simple", "base"), ("Ligature", "ligature"), ("Mark", "mark")):
        for n in gdef_classes[cls]:
            cats[rename.get(n, n)] = cat
    missing = sorted(set(ufo.keys()) - set(cats))
    ufo.lib["public.openTypeCategories"] = {n: cats[n] for n in sorted(cats)}
    for name, xs in carets.items():
        g = ufo[rename.get(name, name)]
        for k, x in enumerate(xs, 1):
            g.appendAnchor({"name": f"caret_{k}", "x": x, "y": 0})
    return missing


def set_info(ufo, ref):
    info = ufo.info
    os2, hhea, post = ref["OS/2"], ref["hhea"], ref["post"]

    info.familyName = FAMILY
    info.styleName = "Regular"
    info.styleMapFamilyName = FAMILY
    info.styleMapStyleName = "regular"
    info.openTypeNamePreferredFamilyName = None
    info.openTypeNamePreferredSubfamilyName = None
    info.postscriptFontName = f"{PS_FAMILY}-Regular"
    info.postscriptFullName = f"{FAMILY} Regular"
    info.postscriptWeightName = None
    info.versionMajor, info.versionMinor = VERSION
    info.openTypeNameVersion = None
    info.copyright = COPYRIGHT
    info.openTypeNameLicense = LICENSE
    info.openTypeNameLicenseURL = LICENSE_URL
    info.openTypeNameDesigner = "Alexey Kryukov; Myia Didot extensions by Gerhard Schaden"
    info.openTypeNameDesignerURL = None
    info.openTypeNameManufacturerURL = None
    info.openTypeOS2VendorID = None
    info.openTypeHeadCreated = None
    info.note = None
    # bit 3: integer ppem, required for hinted TrueType
    info.openTypeHeadFlags = [0, 1, 3]
    info.guidelines = None

    info.xHeight = os2.sxHeight
    info.capHeight = os2.sCapHeight
    info.openTypeOS2TypoAscender = os2.sTypoAscender
    info.openTypeOS2TypoDescender = os2.sTypoDescender
    info.openTypeOS2TypoLineGap = os2.sTypoLineGap
    info.openTypeOS2WinAscent = os2.usWinAscent
    info.openTypeOS2WinDescent = os2.usWinDescent
    info.openTypeHheaAscender = hhea.ascent
    info.openTypeHheaDescender = hhea.descent
    info.openTypeHheaLineGap = hhea.lineGap
    info.openTypeOS2Selection = [7] if os2.fsSelection & (1 << 7) else []
    info.postscriptUnderlinePosition = post.underlinePosition
    info.postscriptUnderlineThickness = post.underlineThickness


def main(import_dir, ref_path, out_path):
    import_dir = Path(import_dir)
    ufo = ufoLib2.Font.open(import_dir / "raw.ufo")
    meta = json.loads((import_dir / "meta.json").read_text(encoding="utf-8"))
    ref = TTFont(ref_path)
    raw_fea = (import_dir / "raw.fea").read_text(encoding="utf-8")

    rename = build_rename_map(ufo)
    rename_glyphs(ufo, rename)

    for g in ufo:
        g.lib.pop("com.fontlab.hintData", None)

    gsub, caps, gdef_classes = split_fea(fea_rename(raw_fea, rename))
    write_features(ufo, gsub, caps)
    import_kerning(ufo, meta["kerning"], rename)
    missing = import_gdef(ufo, gdef_classes, meta["carets"], rename)

    ufo.glyphOrder = [rename.get(n, n) for n in ref.getGlyphOrder() if rename.get(n, n) in ufo]
    set_info(ufo, ref)

    ufo.save(out_path, overwrite=True)
    (Path(out_path).parent / "glyph-renames.json").write_text(
        json.dumps(rename, indent=1, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(f"renamed {len(rename)} glyphs; {len(ufo.groups)} kern groups, "
          f"{len(ufo.kerning)} kern pairs")
    if missing:
        print(f"no GDEF category for {len(missing)} glyphs: {missing[:20]}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
