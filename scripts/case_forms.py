"""Case-sensitive forms (case): punctuation set among capitals.

    python scripts/case_forms.py UFO

Brackets, dashes, guillemets and ¡ ¿ stand where the lowercase wants
them; in all-caps text (case) they move up onto the capitals:
parenleft.case ... are the glyphs themselves as components, raised (and
moved along the slant in the italics), measured on the style's own
glyphs and metrics:

  CENTRED   the ink centred on the capitals (brackets, guillemets, ·, @)
  SCALED    where they stand against the x-height, against the cap
            height (the dashes, a little below the middle as the hyphen is)
  TURNED    ¡ ¿ where ! ? turned about the capitals' middle would stand

A generated block in features.fea (between BEGIN and END) gives them.
make_bold.py and make_italic.py call make() on what they make. Idempotent.
"""

import math
import re
import sys

import ufoLib2

CENTRED = ("parenleft", "parenright", "bracketleft", "bracketright", "braceleft", "braceright",
           "guillemotleft", "guillemotright", "guilsinglleft", "guilsinglright",
           "periodcentered", "at")
SCALED = ("hyphen", "uni2010", "uni2011", "endash", "emdash", "uni2015", "uni2E17")
TURNED = {"exclamdown": "exclam", "questiondown": "question"}
BEGIN = "# BEGIN case-sensitive forms (generated by scripts/case_forms.py; do not edit)"
END = "# END case-sensitive forms"
LEAST = 40  # a smaller rise is left out: the form stays in place (the italic @)


def _ink(font, name):
    b = font[name].getBounds(font)
    return b.yMin, b.yMax


def shift(font, name):
    """How far name rises in all-caps text."""
    cap = font.info.capHeight or 1434
    lo, hi = _ink(font, name)
    if name in TURNED:
        thi = _ink(font, TURNED[name])[1]
        return round(cap - thi - lo)
    if name in SCALED:
        mid = (lo + hi) / 2
        return round(mid * cap / (font.info.xHeight or 884) - mid)
    return round(cap / 2 - (lo + hi) / 2)


def make(font):
    """Make the .case glyphs of font and its case block; returns the pairs."""
    slant = math.tan(math.radians(-(font.info.italicAngle or 0)))
    names = [n for n in CENTRED + SCALED + tuple(TURNED) if n in font and font[n].getBounds(font)]
    pairs = []
    for name in names:
        dy = shift(font, name)
        case = name + ".case"
        if case in font:
            del font[case]
        if abs(dy) < LEAST:
            dy = 0  # every style has the same glyphs
        g = font.newGlyph(case)
        g.width = font[name].width
        g.components.append(ufoLib2.objects.Component(name, (1, 0, 0, 1, round(dy * slant), dy)))
        font.lib.setdefault("public.openTypeCategories", {})[case] = "base"
        pairs.append((name, case))
    made = [c for _, c in pairs]
    font.glyphOrder = [n for n in font.glyphOrder if n not in made] + made
    block = "\n".join([
        BEGIN,
        "lookup caseCaseForms {",
        *(f"    sub \\{a} by \\{b};" for a, b in pairs),
        "} caseCaseForms;",
        "",
        "feature case {",
        "    lookup caseCaseForms;",
        "} case;",
        END,
    ])
    text = font.features.text or ""
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, text, flags=re.DOTALL)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    font.features.text = text
    return pairs


def main(path):
    font = ufoLib2.Font.open(path)
    pairs = make(font)
    font.save()
    print(f"{path}: case forms", " ".join(f"{a} {font[b].components[0].transformation[5]:+}" for a, b in pairs))


if __name__ == "__main__":
    main(sys.argv[1])
