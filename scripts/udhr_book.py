"""A quarto book proof: one page per language, the Universal Declaration of
Human Rights set in Myia Didot.

    python scripts/udhr_book.py FONT_DIR OUT.tex [--cache build/udhr]

The texts are those of the UDHR in Unicode project (maintained by Eric
Muller, https://github.com/eric-muller/udhr; text (c) OHCHR). Missing ones
are downloaded into the cache directory, which is not part of the
repository. Each page: the language's name, its title of the Declaration,
then the preamble and articles until the page is full, cut at a line. The
page is in-quarto, 245 x 320 mm, with margins after the Van de Graaf canon;
12.5/16 pt, justified, babel's hyphenation and language for each language.
`make udhr` writes build/proofs/udhr-quarto.pdf.
"""

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from reference_inputs import fetch_udhr

NS = "{http://efele.net/udhr}"

# UDHR file code, babel language, the language's own name
LANGS = [
    ("eng", "english", "English"), ("fra", "french", "Français"), ("deu_1996", "ngerman", "Deutsch"),
    ("spa", "spanish", "Español"), ("por_PT", "portuguese", "Português"), ("ita", "italian", "Italiano"),
    ("cat", "catalan", "Català"), ("nld", "dutch", "Nederlands"), ("swe", "swedish", "Svenska"),
    ("dan", "danish", "Dansk"), ("nob", "norsk", "Norsk bokmål"), ("isl", "icelandic", "Íslenska"),
    ("fin", "finnish", "Suomi"), ("est", "estonian", "Eesti"), ("lav", "latvian", "Latviešu"),
    ("lit", "lithuanian", "Lietuvių"), ("pol", "polish", "Polski"), ("ces", "czech", "Čeština"),
    ("slk", "slovak", "Slovenčina"), ("slv", "slovenian", "Slovenščina"), ("hrv", "croatian", "Hrvatski"),
    ("hun", "hungarian", "Magyar"), ("ron_2006", "romanian", "Română"), ("tur", "turkish", "Türkçe"),
    ("azj_latn", "azerbaijani", "Azərbaycanca"), ("als", "albanian", "Shqip"), ("mlt", "maltese", "Malti"),
    ("cym", "welsh", "Cymraeg"), ("gle", "irish", "Gaeilge"), ("eus", "basque", "Euskara"),
    ("vie", "vietnamese", "Tiếng Việt"), ("hau_NG", "hausa", "Hausa"), ("yor", "yoruba", "Yorùbá"),
    ("ewe", "ewe", "Eʋegbe"), ("lin", "lingala", "Lingála"),
    ("ell_monotonic", "greek", "Ελληνικά"), ("ell_polytonic", "polytonicgreek", "Ἑλληνική (πολυτονική)"),
    ("rus", "russian", "Русский"), ("ukr", "ukrainian", "Українська"), ("bel", "belarusian", "Беларуская"),
    ("bul", "bulgarian", "Български"), ("srp_cyrl", "serbian", "Српски"), ("mkd", "macedonian", "Македонски"),
]
# fontspec's language names where babel's differ (else fontspec rejects them
# and the page loses its language: no dotted İ for Azerbaijani)
OPENTYPE = {"azerbaijani": "Azeri", "belarusian": "Belarussian"}

SPECIALS = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}

PREAMBLE = r"""% One quarto page per language: the UDHR (UDHR in Unicode project; text (c) OHCHR).
% Generated by scripts/udhr_book.py.
\documentclass[12pt]{article}
\usepackage[paperwidth=245mm,paperheight=320mm,
  inner=27mm,top=36mm,outer=54mm,bottom=71mm]{geometry}  % Van de Graaf proportions
\usepackage[english]{babel}
<PROVIDE>
\babelfont{rm}[Path=<FONTDIR>/, Renderer=HarfBuzz]{MyiaDidot-Regular.otf}
\newcommand\smallcapsfont{\addfontfeature{Letters={SmallCaps,UppercaseSmallCaps}}}
\pagestyle{empty}
\setlength{\parindent}{1.4em}
\emergencystretch=3em \tolerance=600
\newcommand\arttitle[1]{\par\medskip\noindent{\centering\smallcapsfont #1\par}\nobreak\smallskip}
% the language's name and the title, then as much text as fills the page
\newcommand\udhrpage[3]{%
  \setbox4=\vbox{\hsize=\textwidth\centering{\fontsize{24}{28}\selectfont #1\par}\medskip
    {\fontsize{14}{18}\selectfont #2\par}\bigskip\bigskip}%
  % the fil at the top makes every break equally good, so the split takes
  % the last one that fits; the page's fill outranks it afterwards
  \setbox0=\vbox{\vskip 0pt plus 1fil\hsize=\textwidth\fontsize{12.5}{16}\selectfont
    \parindent=1.4em #3}%
  \dimen0=\textheight \advance\dimen0 by -\ht4 \advance\dimen0 by -\dp4
  \advance\dimen0 by -16pt
  \setbox2=\vsplit0 to \dimen0
  \noindent\box4\par\unvbox2\par\vfill\newpage}
\begin{document}
\fontsize{12.5}{16}\selectfont
"""


def tex(s):
    return "".join(SPECIALS.get(c, c) for c in " ".join(s.split()))


def fetch(code, cache):
    return fetch_udhr(code, cache)

def page(path, babel, name):
    root = ET.parse(path).getroot()
    title = root.find(f"{NS}title")
    parts = []
    sections = [root.find(f"{NS}preamble"), *root.findall(f"{NS}article")]
    for section in [s for s in sections if s is not None]:
        head = section.find(f"{NS}title")
        if head is not None and head.text:
            parts.append(rf"\arttitle{{{tex(head.text)}}}")
        parts += [tex(p.text) + r"\par" for p in section.iter(f"{NS}para") if p.text]
    body = "\n".join(parts)
    heading = tex(title.text) if title is not None and title.text else ""
    return (rf"\begin{{otherlanguage}}{{{babel}}}" "\n"
            rf"\udhrpage{{{tex(name)}}}{{{heading}}}{{%" "\n" f"{body}}}\n"
            rf"\end{{otherlanguage}}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("fontdir")
    ap.add_argument("out")
    ap.add_argument("--cache", default="build/udhr")
    args = ap.parse_args()
    cache = Path(args.cache)
    pages, used = [], []
    for code, babel, name in LANGS:
        try:
            path = fetch(code, cache)
        except OSError as e:
            print(f"skipped {code}: {e}", file=sys.stderr)
            continue
        pages.append(page(path, babel, name))
        used.append(babel)
    provide = "\n".join(
        rf"\babelprovide[import{f', language={OPENTYPE[b]}' if b in OPENTYPE else ''}]{{{b}}}"
        for b in sorted(set(used)) if b != "english")
    doc = (PREAMBLE.replace("<PROVIDE>", provide).replace("<FONTDIR>", str(Path(args.fontdir).resolve()))
           + "\n".join(pages) + "\n\\end{document}\n")
    Path(args.out).write_text(doc)
    print(f"{args.out}: {len(pages)} pages")


if __name__ == "__main__":
    main()
