CAP_HEIGHT = 1434
X_HEIGHT = 884
LC_STEM, UC_STEM = 164, 208
DRAFT_KEY = "org.myiadidot.smallcapDraft"
HEIGHT_KEY = "org.myiadidot.smallcapHeight"  # in the UFO's lib
DEFAULT_HEIGHT = 960

# Set by configure() from the UFO's small-cap height.
SC_HEIGHT = SCALE = TOP = TOPCAP = None


def configure(height):
    """Derive the small-cap metrics from their height."""
    global SC_HEIGHT, SCALE, TOP, TOPCAP
    SC_HEIGHT = height
    SCALE = height / CAP_HEIGHT
    # Small caps take the flatter capital accents, as far above the small-cap
    # height as they sit above the cap height (TopCap 1580 at 1434). Top and
    # its kin are kept for marks that have no capital form.
    TOP = height + (1000 - X_HEIGHT)
    TOPCAP = height + (1580 - CAP_HEIGHT)


def stem_for(height):
    """Small-cap stem: between lowercase and capital stems, by height."""
    return round(LC_STEM + (height - X_HEIGHT) / (CAP_HEIGHT - X_HEIGHT) * (UC_STEM - LC_STEM))


configure(DEFAULT_HEIGHT)

BEGIN = "# BEGIN small caps (generated by scripts/smallcaps.py; do not edit)"
END = "# END small caps"


def lower_of(builder, cap):
    u = builder.font[cap].unicode
    lo = chr(u).lower()
    return builder.cmap.get(ord(lo)) if len(lo) == 1 else None


def sc_name(builder, cap):
    lo = lower_of(builder, cap)
    return f"{lo or cap.lower()}.sc"


def is_cap(font, name):
    g = font[name]
    return g.unicode is not None and unicodedata.category(chr(g.unicode)) == "Lu"


def script_of(font, name):
    u = font[name].unicode
    n = unicodedata.name(chr(u), "") if u is not None else ""
    return "grek" if "GREEK" in n else "cyrl" if "CYRILLIC" in n else "latn"


def sc_anchors(cap_glyph, sx):
    """Anchors for a small cap drawn from cap_glyph, horizontally scaled."""
    a = {an.name: (an.x, an.y) for an in cap_glyph.anchors}
    out = []
    if "TopCap" in a:
        x = round(a["TopCap"][0] * sx)
        out += [("Top", x, TOP), ("Acute", x, TOP - 20), ("Grave", x, TOP - 20),
                ("Dotaccent", x, TOP + 20), ("TopCap", x, TOPCAP)]
    for n in ("Bottom", "DotBelow", "Cedilla"):
        if n in a:
            out.append((n, round(a[n][0] * sx), a[n][1]))
    return out


def set_anchors(glyph, anchors):
    for an in list(glyph.anchors):
        glyph.anchors.remove(an)
    for n, x, y in anchors:
        glyph.appendAnchor({"name": n, "x": x, "y": y})


def ink_bounds(font, name):
    pen = BoundsPen(font)
    font[name].draw(pen)
    return pen.bounds


class _SlicePen(BasePen):
    """Collects the x where the outline crosses a horizontal line at y."""

    def __init__(self, glyphset, y):
        super().__init__(glyphset)
        self.y, self.xs = y, []

    def _cross(self, p0, p1):
        (x0, y0), (x1, y1) = p0, p1
        if (y0 - self.y) * (y1 - self.y) < 0:
            self.xs.append(x0 + (self.y - y0) * (x1 - x0) / (y1 - y0))

    def _moveTo(self, p):
        self.cur = self.start = p

    def _lineTo(self, p):
        self._cross(self.cur, p)
        self.cur = p

    def _curveToOne(self, a, b, c):
        p0 = self.cur
        for i in range(1, 33):
            t = i / 32
            m = 1 - t
            q = tuple(m**3 * p0[k] + 3 * m * m * t * a[k] + 3 * m * t * t * b[k] + t**3 * c[k]
                      for k in (0, 1))
            self._cross(self.cur, q)
            self.cur = q

    def _closePath(self):
        self._lineTo(self.start)


def ink_slice(font, name, y):
    pen = _SlicePen(font, y)
    font[name].draw(pen)
    return sorted(pen.xs)


def new_glyph(font, name, width, components=(), anchors=()):
    if name in font:
        del font[name]
    g = font.newGlyph(name)
    g.width = width
    pen = g.getPointPen()
    for base, dx, dy in components:
        pen.addComponent(base, (1, 0, 0, 1, dx, dy))
    set_anchors(g, anchors)
    if name not in font.glyphOrder:
        font.glyphOrder = [*font.glyphOrder, name]
    font.lib.setdefault("public.openTypeCategories", {})[name] = "base"
    return g


def import_drafts(font, drafts, log, redraft=False):
    """Import FontForge drafts. Outlines already in the font are kept, except
    with redraft=True, which replaces those still marked as unreviewed drafts."""
    b = Builder(font)
    for cap in [g.name for g in font if is_cap(font, g.name)]:
        name = sc_name(b, cap)
        if name not in drafts:
            continue
        if name in font and not (redraft and font[name].lib.get(DRAFT_KEY)):
            continue  # never replace edited outlines or a small cap built from components
        d = drafts[name]
        g = new_glyph(font, name, d.width)
        pen = g.getPointPen()
        d.drawPoints(pen)
        sx = d.width / font[cap].width
        set_anchors(g, sc_anchors(font[cap], sx))
        g.lib[DRAFT_KEY] = True
        log.append(f"draft {name} (from {cap}, x{sx:.3f})")


def build_aliases(font, log):
    b = Builder(font)
    for cap in [g.name for g in font if is_cap(font, g.name)]:
        g = font[cap]
        if g.contours or len(g.components) != 1:
            continue
        c = g.components[0]
        if tuple(c.transformation) != (1, 0, 0, 1, 0, 0) or not is_cap(font, c.baseGlyph):
            continue
        base_sc = sc_name(b, c.baseGlyph)
        name = sc_name(b, cap)
        if base_sc not in font or (name in font and font[name].contours):
            continue
        ref = font[base_sc]
        sx = ref.width / font[c.baseGlyph].width
        width = round(ref.width + (g.width - font[c.baseGlyph].width) * sx)
        anchors = [(a.name, a.x, a.y) for a in ref.anchors]
        # the capital's own anchors win (Greek/Cyrillic capitals may differ)
        own = sc_anchors(g, sx)
        if own:
            anchors = own
        new_glyph(font, name, width, [(base_sc, 0, 0)], anchors)
        log.append(f"alias {name} -> {base_sc}")


def lowercase_marks(b, marks):
    return [b.cmap[ord(m)] for m in marks]


def build_accented(font, log, failed):
    b = Builder(font)
    for cap in [g.name for g in font if is_cap(font, g.name)]:
        g = font[cap]
        if script_of(font, cap) == "grek":
            continue  # Greek small caps drop their accents (see the features)
        nfd = unicodedata.normalize("NFD", chr(g.unicode))
        if len(nfd) < 2:
            continue
        name = sc_name(b, cap)
        if name in font and font[name].contours:
            continue
        base_cap = b.cmap.get(ord(nfd[0]))
        if base_cap is None or sc_name(b, base_cap) not in font:
            failed.append(f"{name}: no small cap for base {nfd[0]}")
            continue
        base_sc = sc_name(b, base_cap)
        if cap in SPECIAL:
            continue  # handled in build_specials
        try:
            r = b.compose(name, None, base_sc, lowercase_marks(b, nfd[1:]), upper=True)
        except ValueError as e:
            failed.append(str(e))
            continue
        if name in font:
            del font[name]
        b.write(r)
        log.append(f"accented {name} = " + " + ".join(c.glyph for c in r.components))


def build_lowercase_only(font, log, failed):
    """Small caps for accented lowercase letters with no capital (ǰ, ẖ, ẗ ...)."""
    b = Builder(font)
    for g in list(font):
        if g.unicode is None or g.name.endswith(".sc"):
            continue
        ch = chr(g.unicode)
        up = ch.upper()
        has_capital = len(up) == 1 and ord(up) in b.cmap
        if unicodedata.category(ch) != "Ll" or has_capital or script_of(font, g.name) == "grek":
            continue
        nfd = unicodedata.normalize("NFD", ch)
        name = f"{g.name}.sc"
        if len(nfd) < 2 or (name in font and font[name].contours):
            continue
        base = b.cmap.get(ord(nfd[0]))
        if base is None or f"{base}.sc" not in font:
            continue
        try:
            r = b.compose(name, None, f"{base}.sc", lowercase_marks(b, nfd[1:]), upper=True)
        except ValueError as e:
            failed.append(str(e))
            continue
        if name in font:
            del font[name]
        b.write(r)
        log.append(f"accented {name} (lowercase only)")


def build_specials(font, log, failed):
    b = Builder(font)

    def need(*names):
        missing = [n for n in names if n not in font]
        if missing:
            failed.append(f"specials: missing {missing}")
        return not missing

    if need("s.sc"):
        # ß and ẞ take the small ẞ (drafted from ẞ); SS is the ss02 alternate
        w = font["s.sc"].width
        new_glyph(font, "s_s.sc", 2 * w, [("s.sc", 0, 0), ("s.sc", w, 0)])
        new_glyph(font, "longs.sc", w, [("s.sc", 0, 0)], [(a.name, a.x, a.y) for a in font["s.sc"].anchors])
    if need("i.sc"):
        new_glyph(font, "dotlessi.sc", font["i.sc"].width, [("i.sc", 0, 0)],
                  [(a.name, a.x, a.y) for a in font["i.sc"].anchors])
        try:
            r = b.compose("idotaccent.sc", None, "i.sc", ["uni0307"], upper=True)
            if "idotaccent.sc" in font:
                del font["idotaccent.sc"]
            b.write(r)
        except ValueError as e:
            failed.append(str(e))
    if need("j.sc") and "uni0237" in font:
        new_glyph(font, "uni0237.sc", font["j.sc"].width, [("j.sc", 0, 0)],
                  [(a.name, a.x, a.y) for a in font["j.sc"].anchors])
    if need("k.sc") and "kgreenlandic" in font:
        new_glyph(font, "kgreenlandic.sc", font["k.sc"].width, [("k.sc", 0, 0)])
    if need("i.sc", "j.sc") and "IJ" in font:
        ij = font["IJ"]
        jdx = next((c.transformation[4] for c in ij.components if c.baseGlyph == "J"), font["I"].width)
        dx = round(jdx * font["i.sc"].width / font["I"].width)
        new_glyph(font, "ij.sc", dx + font["j.sc"].width, [("i.sc", 0, 0), ("j.sc", dx, 0)])

    # Latvian/Livonian comma below, Lcaron's apostrophe: mirror the capital.
    for cap in ("Gcommaaccent", "Kcommaaccent", "Lcommaaccent", "Ncommaaccent", "Rcommaaccent"):
        base = cap[0]
        if cap not in font or not need(f"{base.lower()}.sc"):
            continue
        base_sc = f"{base.lower()}.sc"
        bottom = {a.name: (a.x, a.y) for a in font[base_sc].anchors}.get("Bottom")
        comma = next((c for c in font[cap].components if c.baseGlyph == "commaaccent"), None)
        if bottom is None or comma is None:
            failed.append(f"{cap}: no Bottom anchor on {base_sc} or no comma in {cap}")
            continue
        cap_bottom = {a.name: (a.x, a.y) for a in font[base].anchors}["Bottom"]
        dx = comma.transformation[4] - cap_bottom[0] + bottom[0]
        new_glyph(font, sc_name(b, cap), font[base_sc].width,
                  [(base_sc, 0, 0), ("commaaccent", round(dx), 0)])
    def beside_l(cap, dy=None):
        """Small cap of Ŀ/Ľ: l.sc plus the capital's mark, which keeps its
        size. Its centre goes at the same fraction of the way from the stem
        to the end of the foot as in the capital; vertically at the same
        height fraction, or shifted by dy."""
        mark = next(c for c in font[cap].components if c.baseGlyph != "L")
        mx0, my0, mx1, my1 = ink_bounds(font, mark.baseGlyph)
        cx = mark.transformation[4] + (mx0 + mx1) / 2
        cy = mark.transformation[5] + (my0 + my1) / 2
        stem = max(x for x in ink_slice(font, "L", cy) if x < cx)
        foot = ink_bounds(font, "L")[2]
        t = (cx - stem) / (foot - stem)
        sc_cy = cy * SCALE if dy is None else cy + dy
        sc_stem = max(x for x in ink_slice(font, "l.sc", sc_cy) if x < font["l.sc"].width / 2)
        sc_cx = sc_stem + t * (ink_bounds(font, "l.sc")[2] - sc_stem)
        return mark.baseGlyph, round(sc_cx - (mx0 + mx1) / 2), round(sc_cy - (my0 + my1) / 2)

    if "Ldot" in font and need("l.sc"):
        new_glyph(font, "ldot.sc", font["l.sc"].width, [("l.sc", 0, 0), beside_l("Ldot")])
    if "Lcaron" in font and need("l.sc"):
        # the apostrophe keeps its height above the letter
        new_glyph(font, "lcaron.sc", font["l.sc"].width,
                  [("l.sc", 0, 0), beside_l("Lcaron", dy=-(CAP_HEIGHT - SC_HEIGHT))])
    # Greek: small caps keep the dialytika only.
    for lo in ("iotadieresis", "upsilondieresis"):
        if lo in font:
            base = {"iotadieresis": "iota.sc", "upsilondieresis": "upsilon.sc"}[lo]
            if not need(base):
                continue
            try:
                r = b.compose(f"{lo}.sc", None, base, ["uni0308"], upper=True)
                if r.name in font:
                    del font[r.name]
                b.write(r)
            except ValueError as e:
                failed.append(str(e))
    log.append("specials built")


def scale_kerning(font, log):
    b = Builder(font)
    # Each small cap takes the kerning of its canonical capital only (the
    # uppercase of its lowercase letter): Θ, not ϴ, for theta.sc.
    cap_sc = {}
    for g in font:
        if not is_cap(font, g.name):
            continue
        sc = sc_name(b, g.name)
        lo = lower_of(b, g.name)
        canonical = lo is None or chr(font[lo].unicode).upper() == chr(g.unicode)
        if sc in font and canonical and sc not in cap_sc.values():
            cap_sc[g.name] = sc
    new_groups = {}
    for gname, members in list(font.groups.items()):
        if not gname.startswith(("public.kern1.", "public.kern2.")) or gname.endswith(".sc"):
            continue
        scs = [cap_sc[m] for m in members if m in cap_sc]
        if scs:
            new_groups[gname] = (gname + ".sc", scs)
    for gname, (scname, scs) in new_groups.items():
        font.groups[scname] = scs

    def side(item):
        if item in new_groups:
            return new_groups[item][0]
        return cap_sc.get(item)

    for k in [k for k in font.kerning if k[0].endswith(".sc") or k[1].endswith(".sc")]:
        del font.kerning[k]
    n = 0
    for (left, right), value in list(font.kerning.items()):
        l2, r2 = side(left), side(right)
        if l2 and r2:
            font.kerning[(l2, r2)] = round(value * SCALE)
            n += 1
    log.append(f"kerning: {len(new_groups)} groups, {n} pairs scaled by {SCALE:.3f}")
    # Typed Catalan l·l: kern the middle dot over the foot of l.sc, where
    # ŀ (ldot.sc) has it, and keep the total advance of ŀl.
    if all(n in font for n in ("ldot.sc", "l.sc", "periodcentered")):
        dot = next(c for c in font["ldot.sc"].components if c.baseGlyph != "l.sc")
        target = dot.transformation[4] + ink_bounds(font, dot.baseGlyph)[0]
        left = font["l.sc"].width + ink_bounds(font, "periodcentered")[0]
        k1 = round(target - left)
        k2 = font["ldot.sc"].width - font["l.sc"].width - k1 - font["periodcentered"].width
        font.kerning[("l.sc", "periodcentered")] = k1
        font.kerning[("periodcentered", "l.sc")] = k2
        log.append(f"kerning: l.sc·l.sc {k1}/{k2}")


def smcp_map(font):
    """(glyph -> small cap) for smcp and c2sc, and (glyph -> [small caps]) for
    Greek letters with ypogegrammeni/prosgegrammeni, which take an adscript
    iota in small caps (ᾳ -> ΑΙ)."""
    b = Builder(font)
    smcp, c2sc = {}, {}
    multi_lo, multi_up = {}, {}
    for g in font:
        if g.unicode is None or g.name.endswith(".sc"):
            continue
        ch = chr(g.unicode)
        cat = unicodedata.category(ch)
        if cat == "Lt":
            cat = "Lu"  # Greek capitals with prosgegrammeni (ᾼ) are titlecase
        if cat not in ("Ll", "Lu"):
            continue
        if cat == "Lu":
            target = sc_name(b, g.name)
        else:
            target = f"{g.name}.sc"
        iota = False
        if target not in font and script_of(font, g.name) == "grek":
            # strip Greek accents, keep the dialytika; ypogegrammeni -> adscript
            nfd = unicodedata.normalize("NFD", ch)
            iota = "\u0345" in nfd
            kept = nfd[0] + ("\u0308" if "\u0308" in nfd else "")
            base_ch = unicodedata.normalize("NFC", kept).lower()
            if len(base_ch) == 1 and ord(base_ch) in b.cmap:
                target = f"{b.cmap[ord(base_ch)]}.sc"
        if target not in font:
            continue
        if iota and "iota.sc" in font:
            (multi_up if cat == "Lu" else multi_lo)[g.name] = [target, "iota.sc"]
            continue
        (c2sc if cat == "Lu" else smcp)[g.name] = target
    # ς and the symbol variants follow their letters
    for lo, sc in (("sigma1", "sigma.sc"), ("uni03C2", "sigma.sc")):
        if lo in font and sc in font:
            smcp[lo] = sc
    return smcp, c2sc, multi_lo, multi_up


GREEK_MARK_PARTS = ("uni0313", "uni0314", "uni0342", "uni0343", "uni0344")


def greek_marks(font):
    """Mark glyphs that can follow a Greek letter once ccmp has run."""
    cats = font.lib.get("public.openTypeCategories", {})
    out = []
    for name, cat in cats.items():
        if cat != "mark" or name not in font:
            continue
        if (name.endswith((".grek", ".iota")) or any(p in name for p in GREEK_MARK_PARTS)
                or name in ("acutecomb", "gravecomb", "uni0308", "macroncmb", "brevecmb")):
            out.append(name)
    return sorted(out)


def has_dieresis(mark):
    return "uni0308" in mark or "uni0344" in mark


def features_block(font):
    smcp, c2sc, multi_lo, multi_up = smcp_map(font)
    # After a small cap, a combining accent takes its capital form, as in the
    # precomposed small caps (ccmp may have picked the narrow ".i" form).
    cats = font.lib.get("public.openTypeCategories", {})
    marks_fix = []
    for g in font:
        if g.name.endswith(".cap") and cats.get(g.name) == "mark":
            plain = g.name[: -len(".cap")]
            if plain in font:
                marks_fix.append((plain, g.name))
                if plain + ".i" in font:
                    marks_fix.append((plain + ".i", g.name))
        if g.name.endswith(".cyrcap") and cats.get(g.name) == "mark":
            stem = g.name[: -len(".cyrcap")]
            if stem + ".cyrl" in font:
                marks_fix.append((stem + ".cyrl", g.name))
    cap_marks = sorted({cap for _, cap in marks_fix})
    sc_glyphs = sorted({*smcp.values(), *c2sc.values(), *(x for v in (*multi_lo.values(), *multi_up.values()) for x in v)})
    greek_sc = sorted({t for k, t in [*smcp.items(), *c2sc.items()] if script_of(font, k) == "grek"})
    gmarks = greek_marks(font)
    lines = [BEGIN, ""]
    turkish = "i" in smcp and "idotaccent.sc" in font
    if turkish:
        # defined first: GSUB applies lookups in list order, so this must run
        # before SmallCapsLower turns i into the dotless small cap
        lines.append("lookup SmallCapsTurkish {\n    sub \\i by \\idotaccent.sc;\n} SmallCapsTurkish;\n")
    lines.append("lookup SmallCapsLower {")
    lines += [f"    sub \\{k} by \\{v};" for k, v in sorted(smcp.items())]
    lines.append("} SmallCapsLower;\n")
    lines.append("lookup SmallCapsUpper {")
    lines += [f"    sub \\{k} by \\{v};" for k, v in sorted(c2sc.items())]
    lines.append("} SmallCapsUpper;\n")
    for lname, mp in (("SmallCapsLowerIota", multi_lo), ("SmallCapsUpperIota", multi_up)):
        lines.append(f"lookup {lname} {{")
        lines += [f"    sub \\{k} by " + " ".join(f"\\{x}" for x in v) + ";" for k, v in sorted(mp.items())]
        lines.append(f"}} {lname};\n")
    # Decomposed Greek: accents after a small cap are dropped, the dialytika
    # kept (ϊ, ϋ), the ypogegrammeni becomes an adscript iota. Two passes for
    # two marks in a row.
    dier = {"iota.sc": "iotadieresis.sc", "upsilon.sc": "upsilondieresis.sc"}
    for k in (1, 2):
        lines.append(f"lookup SmallCapsGreekAccents{k} {{")
        for sc in greek_sc:
            for m in gmarks:
                out = dier.get(sc, sc) if has_dieresis(m) and dier.get(sc) in font else sc
                lines.append(f"    sub \\{sc} \\{m} by \\{out};")
        lines.append(f"}} SmallCapsGreekAccents{k};\n")
    lines.append("lookup SmallCapsGreekIota {")
    lines.append("    sub [" + " ".join(f"\\{n}" for n in greek_sc) + "] \\uni0345' by \\iota.sc;")
    lines.append("} SmallCapsGreekIota;\n")
    lines.append("@SmallCaps = [" + " ".join(f"\\{n}" for n in sc_glyphs) + "];\n")
    if "germandbls.sc" in font and "s_s.sc" in font:
        lines.append("lookup SmallCapSharpSAsSS {\n    sub \\germandbls.sc by \\s_s.sc;\n} SmallCapSharpSAsSS;\n")
    lines.append("lookup SmallCapMarkForms {")
    lines.append("    # combining accents take their capital form after a small cap")
    lines.append("    lookupflag 0;")
    for m, base in marks_fix:
        lines.append(f"    sub @SmallCaps [\\{m}]' by \\{base};")
    # past a mark below (ậ), and the second accent of a stack follows the
    # first into its capital form
    b = Builder(font)
    below = sorted(n for n, c in cats.items() if c == "mark" and n in font and b.mark_side(n) == "bottom")
    below_cls = "[" + " ".join(f"\\{n}" for n in below) + "]"
    caps = "[" + " ".join(f"\\{c}" for c in cap_marks) + "]"
    for m, base in marks_fix:
        lines.append(f"    sub @SmallCaps {below_cls} [\\{m}]' by \\{base};")
        lines.append(f"    sub {caps} [\\{m}]' by \\{base};")
    lines.append("} SmallCapMarkForms;\n")
    for tag, lookup in (("smcp", "SmallCapsLower"), ("c2sc", "SmallCapsUpper")):
        # default lookups first: they register for every language system, and
        # a language block below keeps them (include_dflt)
        lines.append(f"feature {tag} {{")
        lines.append(f"    lookup {lookup};")
        lines.append(f"    lookup {lookup}Iota;")
        lines.append("    lookup SmallCapsGreekAccents1;")
        lines.append("    lookup SmallCapsGreekAccents2;")
        lines.append("    lookup SmallCapsGreekIota;")
        lines.append("    lookup SmallCapMarkForms;")
        if tag == "smcp" and turkish:
            lines.append("    script latn;")
            for lang in ("TRK", "AZE", "CRT"):
                lines.append(f"    language {lang};\n    lookup SmallCapsTurkish;")
        lines.append(f"}} {tag};\n")
    if "germandbls.sc" in font and "s_s.sc" in font:
        lines.append("feature ss02 {")
        lines.append('    featureNames { name "Small caps: SS for ß and ẞ"; };')
        lines.append("    lookup SmallCapSharpSAsSS;")
        lines.append("} ss02;\n")
    lines.append(END)
    return "\n".join(lines), len(smcp), len(c2sc)


def write_features(font, log):
    block, n_lo, n_up = features_block(font)
    text = font.features.text
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        anchor = "} loclss01RomanianVariantForms;"
        i = text.index(anchor) + len(anchor)
        text = text[:i] + "\n\n" + block + "\n" + text[i:]
    font.features.text = text
    log.append(f"features: smcp {n_lo} glyphs, c2sc {n_up} glyphs")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ufo")
    ap.add_argument("--drafts", help="UFO written by scripts/smallcaps_draft.py")
    ap.add_argument("--redraft", action="store_true",
                    help="replace small caps still marked as unreviewed drafts")
    ap.add_argument("--height", type=int,
                    help=f"set the small-cap height (stored in lib {HEIGHT_KEY})")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    font = ufoLib2.Font.open(args.ufo)
    if args.height:
        font.lib[HEIGHT_KEY] = args.height
    configure(font.lib.get(HEIGHT_KEY, DEFAULT_HEIGHT))
    log, failed = [], []
    if args.drafts:
        drafts = ufoLib2.Font.open(args.drafts)
        import_drafts(font, {g.name: g for g in drafts if g.name.endswith(".sc")}, log,
                      redraft=args.redraft)
    build_aliases(font, log)
    build_accented(font, log, failed)
    build_specials(font, log, failed)
    build_lowercase_only(font, log, failed)
    scale_kerning(font, log)
    write_features(font, log)
    font.save()

    kinds = {}
    for line in log:
        kinds[line.split()[0]] = kinds.get(line.split()[0], 0) + 1
    for line in log if args.verbose else [m for m in log if not m.startswith(("draft", "alias", "accented"))]:
        print(line)
    print("counts:", kinds)
    for f in failed:
        print("FAIL", f)


if __name__ == "__main__":
    main()
