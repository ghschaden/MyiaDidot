"""Small capitals: import drafts, build the rest, write smcp/c2sc.

    python scripts/smallcaps.py UFO --drafts DRAFT.ufo   # import new drafts
    python scripts/smallcaps.py UFO                      # rebuild derived parts

Small caps are named after the lowercase letter ("a.sc"; "idotaccent.sc"
for İ, whose lowercase is two characters). They come in four kinds:

* drafts: outlines from scripts/smallcaps_draft.py (FontForge), imported
  once and then edited by hand; marked with lib key DRAFT_KEY until someone
  clears it after review. Existing outlines are never overwritten.
* aliases: a capital that is a single component of another (Α -> A,
  А -> A) gives a small cap that is a component of the other's small cap.
* accented: from the capital's decomposition, on the small-cap base, with
  lowercase accents raised to the small-cap height (scripts/composites.py).
* specials: ß, ı, ĳ, ſ, ĸ, Latvian comma accents, Ľ.

Anchors of drafts are derived from the capital's, scaled horizontally;
kerning between capitals is copied to their small caps, scaled. The OpenType
code is the block between the BEGIN/END markers in features.fea.
"""

