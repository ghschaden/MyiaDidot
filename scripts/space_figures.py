"""Figures spaced as text, tabular ones on request.

    python scripts/space_figures.py UFO

The default figures are proportional (2026-11-14: as Charis, Libertinus
and most book faces set them; old documents reflow where they have
figures): the lining ones each spaced by their shapes, each side's optical
space across the figure height made that of the 0 (the widest figure,
fitted as it is), the old-style ones by theirs across the x-height, each
side made that of n and o; across the foot serifs' band a lining figure's
ink keeps at least I's mean side (the 1 and 4 would meet their
neighbours' feet). tnum gives the tabular forms, zero.tf ... and
zerooldstyle.tf ... (components, each centred in the 0's width), from a
generated block in features.fea (between BEGIN and END); pnum turns them
back, lnum turns old-style figures into lining ones, and zero gives the
slashed zero (zero.zero, zerooldstyle.zero, made here of the style's own
zeros: slashed(); drafts) in whichever of the four forms the figure has by
then. A side within a unit of its fit is left (a rerun keeps it).
make_bold.py and make_italic.py call space() on what they make; on the
Regular it is one of its generated parts (make check-regular).
"""

import math
import re
import sys
from pathlib import Path

import pathops
import ufoLib2
from fontTools.pens.recordingPen import DecomposingRecordingPen, RecordingPen
from fontTools.pens.transformPen import TransformPen

sys.path.insert(0, str(Path(__file__).resolve().parent))

FIGURES = ("zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine")
BEGIN = "# BEGIN figure forms (generated by scripts/space_figures.py; do not edit)"
END = "# END figure forms"
SLASHES = {"zero": 60, "zerooldstyle": 50}  # the slashed zeros' angles, upright frame
SLASH_WEIGHT = 1.15
FOOT = 0.06  # the foot serifs' band, of the cap height (I's serif and bracket)  # the slash against the zero's hairline (Ø's in the Regular)
# the block's earlier markers, replaced on a run
OLD_BEGIN = "# BEGIN tabular old-style figures (generated by scripts/space_figures.py; do not edit)"
OLD_END = "# END tabular old-style figures"


def _path(font, name):
    slant = math.tan(math.radians(-(font.info.italicAngle or 0)))
    p = pathops.Path()
    rec = DecomposingRecordingPen(font)
    font[name].draw(rec)
    rec.replay(TransformPen(p.getPen(), (1, 0, -slant, 1, 0, 0)))  # judged upright
    return pathops.simplify(p)


def _runs(path, y):
    r = pathops.Path()
    pen = r.getPen()
    pen.moveTo((-9000, y - 0.5))
    pen.lineTo((9000, y - 0.5))
    pen.lineTo((9000, y + 0.5))
    pen.lineTo((-9000, y + 0.5))
    pen.closePath()
    q = pathops.op(path, r, pathops.PathOp.INTERSECTION)
    return sorted((c.bounds[0], c.bounds[2]) for c in q.contours)


def optical(font, name, h, depth=0.2, steps=40):
    """(left, right) optical side space over 0..h, deep white clipped."""
    path = _path(font, name)
    w = font[name].width
    out = []
    for which in "LR":
        vals = []
        for i in range(steps):
            rr = _runs(path, h * (i + 0.5) / steps)
            vals.append(None if not rr else (rr[0][0] if which == "L" else w - rr[-1][1]))
        real = [v for v in vals if v is not None]
        near = min(real)
        out.append(sum(min(v, near + depth * h) if v is not None else near + depth * h for v in vals) / steps)
    return out


def counter_diagonal(ink, angle, frac):
    """The ends of a stroke across the counter of ink (a 0): through its
    middle at angle (degrees), each end frac of the way from where it
    leaves the counter to where it leaves the ink (inside the stroke)."""
    from derive import BIG, path_op, stroke

    def area(c):
        return (c.bounds[2] - c.bounds[0]) * (c.bounds[3] - c.bounds[1])

    filled = pathops.Path()
    max(ink.contours, key=area).draw(filled.getPen())
    hole = pathops.Path()
    max(path_op(filled, ink, "DIFFERENCE").contours, key=area).draw(hole.getPen())
    x0, y0, x1, y1 = hole.bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    ux, uy = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    rec = RecordingPen()
    stroke(rec, (cx - ux * BIG, cy - uy * BIG), (cx + ux * BIG, cy + uy * BIG), 1)
    line = pathops.Path()
    rec.replay(line.getPen())
    i0, j0, i1, j1 = path_op(hole, line, "INTERSECTION").bounds
    o0, p0, o1, p1 = path_op(filled, line, "INTERSECTION").bounds
    return ((i0 + (o0 - i0) * frac, j0 + (p0 - j0) * frac),
            (i1 + (o1 - i1) * frac, j1 + (p1 - j1) * frac))


def slashed(font):
    """The slashed zeros (zero.zero, zerooldstyle.zero) made of the font's
    own zeros as they are now: a stroke across the counter at SLASHES'
    angle (upright frame), as heavy as the zero's hairline times
    SLASH_WEIGHT, its ends buried halfway into the ink; the zero's width.
    A draft until reviewed (the lib key kept from the glyph replaced, or
    from the source style's copy)."""
    from built_from import stamp
    from derive import DRAFT_KEY, draw_path, path_op, stroke

    slant = math.tan(math.radians(-(font.info.italicAngle or 0)))
    for base, angle in SLASHES.items():
        name = base + ".zero"
        if base not in font or not font[base].contours:
            continue
        up = _path(font, base)
        x0, _, x1, _ = up.bounds
        cx = (x0 + x1) / 2
        hair = path_op(up, _rect(cx - 0.5, -9000, cx + 0.5, 9000), "INTERSECTION")
        t = min(c.bounds[3] - c.bounds[1] for c in hair.contours) * SLASH_WEIGHT
        rec = RecordingPen()
        stroke(TransformPen(rec, (1, 0, slant, 1, 0, 0)), *counter_diagonal(up, angle, 0.5), t)
        ink, bar = pathops.Path(), pathops.Path()
        rp = DecomposingRecordingPen(font)
        font[base].draw(rp)
        rp.replay(ink.getPen())
        rec.replay(bar.getPen())
        # each simplified on its own: wound against each other in one path,
        # the slash would cancel the ink it crosses
        ink = path_op(pathops.simplify(ink), pathops.simplify(bar), "UNION")
        draft = font[name].lib.get(DRAFT_KEY, True) if name in font else True
        lib = dict(font[name].lib) if name in font else {}
        if name in font:
            del font[name]
        g = font.newGlyph(name)
        g.width = font[base].width
        draw_path(font, font[base], g, ink)
        g.lib.update(lib)
        if font.info.italicAngle:
            g.lib["org.myiadidot.italicSource"] = "derived"
        # reviewed: the key kept false (absent, the next run would take it
        # for a new draft)
        g.lib[DRAFT_KEY] = bool(draft)
        stamp(font, name, [base])  # the zero it was made of (built_from.py)
        font.lib.setdefault("public.openTypeCategories", {})[name] = "base"
        if name not in font.glyphOrder:
            order = list(font.glyphOrder)
            order.insert(order.index(base) + 1, name)
            font.glyphOrder = order


def _rect(x0, y0, x1, y1):
    p = pathops.Path()
    pen = p.getPen()
    pen.moveTo((x0, y0))
    pen.lineTo((x1, y0))
    pen.lineTo((x1, y1))
    pen.lineTo((x0, y1))
    pen.closePath()
    return p


def foot_sides(font, name):
    """(left, right): the ink's nearest approach to each side of the
    advance across the foot serifs' band (0..FOOT of the cap height),
    judged upright."""
    path = _path(font, name)
    w = font[name].width
    left = right = math.inf
    for y in range(0, round(FOOT * (font.info.capHeight or 1434)), 4):
        rr = _runs(path, y)
        if rr:
            left, right = min(left, rr[0][0]), min(right, w - rr[-1][1])
    return left, right


def _fit(font, name, h, target, floor=None):
    """name moved and widened so each side's optical space over 0..h is
    target, and its ink across the foot band no nearer the side than floor
    (if given); a unit either way is the measure's rounding, left. Returns
    the change of its left side."""
    g = font[name]
    left, right = optical(font, name, h)
    dl, dr = round(target - left), round(target - right)
    if floor is not None:
        fl, fr = foot_sides(font, name)
        dl, dr = max(dl, round(floor - fl)), max(dr, round(floor - fr))
    dl, dr = (0 if abs(dl) <= 1 else dl), (0 if abs(dr) <= 1 else dr)
    for c in g.contours:
        for p in c.points:
            p.x += dl
    for c in g.components:
        c.transformation = c.transformation[:4] + (c.transformation[4] + dl, c.transformation[5])
    for a in g.anchors:
        a.x += dl
    g.width += dl + dr
    return dl


def space(font):
    """Space the figures of font (proportional by default) and make their
    tabular .tf forms; returns the old-style figures spaced."""
    xh = font.info.xHeight or 884
    ref = [v for n in ("n", "o") for v in optical(font, n, xh)]
    target = sum(ref) / len(ref)
    done = []
    for d in FIGURES:
        name = d + "oldstyle"
        if name not in font or not font[name].contours:
            continue
        _fit(font, name, xh, target)
        done.append(name)
    # the lining figures, as the 0 is (the widest figure; H and O would
    # space them looser still)
    ch = font.info.capHeight or 1434
    ref = optical(font, "zero", ch)
    target = sum(ref) / len(ref)
    lining = [d for d in FIGURES if d in font and (font[d].contours or font[d].components)]
    # the feet stand off the side as I's do (the 1's foot serifs met in 11
    # and H1, the 4's in 41: 2026-11-14, proofs/figures-feet-2026-11-14.pdf)
    floor = sum(foot_sides(font, "I")) / 2
    for d in lining:
        _fit(font, d, ch, target, floor)
    slashed(font)  # of the zeros as spaced
    # the tabular forms: each figure centred in the 0's width
    tab = font["zero"].width
    tabular = [n for n in lining + ["zero.zero"] + done + ["zerooldstyle.zero"] if n in font]
    for name in tabular:
        _component(font, name + ".tf", name, tab, round((tab - font[name].width) / 2))
    # the proportional lining figures had their own glyphs before 2026-11-14
    gone = [d + ".pf" for d in FIGURES + ("zero.zero",) if d + ".pf" in font]
    for name in gone:
        del font[name]
        font.lib.get("public.openTypeCategories", {}).pop(name, None)
    if gone:
        for pair in [k for k in font.kerning if set(k) & set(gone)]:
            del font.kerning[pair]
        for members in font.groups.values():
            members[:] = [m for m in members if m not in gone]
    made = [n + ".tf" for n in tabular]
    font.glyphOrder = [n for n in font.glyphOrder if n not in made and n not in gone] + made
    if done:
        block = "\n".join([BEGIN] + _rules(font, done) + [END])
        text = font.features.text or ""
        for begin, end in ((BEGIN, END), (OLD_BEGIN, OLD_END)):
            if begin in text:
                text = re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda m: block, text, flags=re.DOTALL)
                break
        else:
            text = text.rstrip("\n") + "\n\n" + block + "\n"
        font.features.text = text
    if font.info.styleName == "Regular":
        # Preserve the reviewed proportional drawings and their optical fit.
        from oldstyle_figures import finish

        finish(font)
    return done


def _component(font, name, base, width, dx):
    if name in font:
        del font[name]
    g = font.newGlyph(name)
    g.width = width
    g.components.append(ufoLib2.objects.Component(base, (1, 0, 0, 1, dx, 0)))
    font.lib.setdefault("public.openTypeCategories", {})[name] = "base"


def _lookup(name, pairs):
    return [f"lookup {name} {{"] + [f"    sub \\{a} by \\{b};" for a, b in pairs] + [f"}} {name};", ""]


def _feature(tag, lookup):
    return [f"feature {tag} {{", f"    lookup {lookup};", f"}} {tag};", ""]


def _rules(font, done):
    """lnum, pnum, tnum and zero, in that order: lnum before tnum (old-style
    figures made lining, then tabular), zero last (on any form)."""
    lining = [n[:-8] for n in done]
    tabular = [n for n in FIGURES + tuple(done) if n + ".tf" in font]
    lines = _lookup("lnumLiningFigures", [(n, d) for n, d in zip(done, lining)]
                    + [(n + ".tf", d + ".tf") for n, d in zip(done, lining) if n + ".tf" in font and d + ".tf" in font])
    lines += _lookup("pnumProportionalFigures", [(n + ".tf", n) for n in tabular])
    lines += _lookup("tnumTabularFigures", [(n, n + ".tf") for n in tabular])
    zero = [(a, b) for a, b in (("zero", "zero.zero"), ("zero.tf", "zero.zero.tf"),
                                ("zerooldstyle", "zerooldstyle.zero"),
                                ("zerooldstyle.tf", "zerooldstyle.zero.tf")) if a in font and b in font]
    if zero:
        lines += _lookup("zeroSlashedZero", zero)
    lines += _feature("lnum", "lnumLiningFigures") + _feature("pnum", "pnumProportionalFigures")
    lines += _feature("tnum", "tnumTabularFigures")
    if zero:
        lines += _feature("zero", "zeroSlashedZero")
    return lines[:-1]


def main(path):
    font = ufoLib2.Font.open(path)
    done = space(font)
    font.save()
    print(f"{path}: figures spaced, tnum gives the tabular forms ({font['zero'].width}):",
          " ".join(f"{d} {font[d].width}" for d in FIGURES), "|",
          " ".join(f"{n[:-8]} {font[n].width}" for n in done))


if __name__ == "__main__":
    main(sys.argv[1])
