"""Old-style figures spaced as text, tabular ones on request.

    python scripts/space_figures.py UFO

The old-style figures stood in the lining figures' tabular cells (the 1
alone in a cell as wide as the 0); as text figures they are spaced by
their own shapes: each side's optical space (the white beside it across
the x-height, deep white clipped, as letterspacing tools measure it) made
that of n and o. Tabular old-style figures for tables stay at hand:
zerooldstyle.tf ... (components, centred in the lining figures' width),
which tnum gives (a generated block in features.fea, between BEGIN and END;
the lining figures are tabular as they are). make_bold.py and
make_italic.py call space() on what they make.
"""

import math
import re
import sys

import pathops
import ufoLib2
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.transformPen import TransformPen

FIGURES = ("zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine")
BEGIN = "# BEGIN tabular old-style figures (generated by scripts/space_figures.py; do not edit)"
END = "# END tabular old-style figures"


def _path(font, name):
    slant = math.tan(math.radians(-(font.info.italicAngle or 0)))
    p = pathops.Path()
    rec = DecomposingRecordingPen(font)
    font[name].draw(rec)
    rec.replay(TransformPen(p.getPen(), (1, 0, -slant, 1, 0, 0)))  # judged upright
    return pathops.simplify(p)


def _runs(path, y):
    r = pathops.Path()
    pen = r.getPen()
    pen.moveTo((-9000, y - 0.5))
    pen.lineTo((9000, y - 0.5))
    pen.lineTo((9000, y + 0.5))
    pen.lineTo((-9000, y + 0.5))
    pen.closePath()
    q = pathops.op(path, r, pathops.PathOp.INTERSECTION)
    return sorted((c.bounds[0], c.bounds[2]) for c in q.contours)


def optical(font, name, h, depth=0.2, steps=40):
    """(left, right) optical side space over 0..h, deep white clipped."""
    path = _path(font, name)
    w = font[name].width
    out = []
    for which in "LR":
        vals = []
        for i in range(steps):
            rr = _runs(path, h * (i + 0.5) / steps)
            vals.append(None if not rr else (rr[0][0] if which == "L" else w - rr[-1][1]))
        real = [v for v in vals if v is not None]
        near = min(real)
        out.append(sum(min(v, near + depth * h) if v is not None else near + depth * h for v in vals) / steps)
    return out


def space(font):
    """Space the old-style figures of font (and make their .tf); returns
    the names spaced."""
    xh = font.info.xHeight or 884
    ref = [v for n in ("n", "o") for v in optical(font, n, xh)]
    target = sum(ref) / len(ref)
    done = []
    for d in FIGURES:
        name = d + "oldstyle"
        if name not in font or not font[name].contours:
            continue
        g = font[name]
        left, right = optical(font, name, xh)
        dl, dr = round(target - left), round(target - right)
        for c in g.contours:
            for p in c.points:
                p.x += dl
        for a in g.anchors:
            a.x += dl
        g.width += dl + dr
        done.append(name)
    # tabular old-style figures: the proportional ones centred in the
    # lining figures' (tabular) width
    tab = font["zero"].width
    for name in done:
        tf = name + ".tf"
        if tf in font:
            del font[tf]
        g = font.newGlyph(tf)
        g.width = tab
        g.components.append(ufoLib2.objects.Component(name, (1, 0, 0, 1, round((tab - font[name].width) / 2), 0)))
        font.lib.setdefault("public.openTypeCategories", {})[tf] = "base"
    if done:
        order = [n for n in font.glyphOrder if not n.endswith("oldstyle.tf")]
        font.glyphOrder = order + [n + ".tf" for n in done]
        lines = [BEGIN, "lookup tnumOldstyleFigures {"]
        lines += [f"    sub \\{n} by \\{n}.tf;" for n in done]
        lines += ["} tnumOldstyleFigures;", "", "feature tnum {", "    lookup tnumOldstyleFigures;",
                  "} tnum;", END]
        block = "\n".join(lines)
        text = font.features.text or ""
        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, text, flags=re.DOTALL)
        else:
            text = text.rstrip("\n") + "\n\n" + block + "\n"
        font.features.text = text
    return done


def main(path):
    font = ufoLib2.Font.open(path)
    done = space(font)
    font.save()
    print(f"{path}: {len(done)} old-style figures spaced, tnum gives their tabular forms:",
          " ".join(f"{n[:-8]} {font[n].width}" for n in done))


if __name__ == "__main__":
    main(sys.argv[1])
