"""Capital spacing (cpsp): capitals set a little apart in all-caps text.

    python scripts/cpsp.py UFO

Every capital (Unicode Lu/Lt, Latin, Greek, Cyrillic, ...) and its
unencoded forms (Ș's Romanian form, Ӏ ..., not the small caps) moves
right by SPACE and gains twice that in advance: a generated block in
features.fea, between BEGIN and END. Run on the Regular: the other styles
take its features (make_bold.py scales the values with the Bold's widths).
Idempotent.
"""

import re
import sys
import unicodedata

import ufoLib2

SPACE = 10  # units added on each side (5/1000 em)
BEGIN = "# BEGIN capital spacing (generated by scripts/cpsp.py; do not edit)"
END = "# END capital spacing"


def capitals(font):
    caps = {g.name for g in font if any(unicodedata.category(chr(u)) in ("Lu", "Lt") for u in g.unicodes)}
    forms = {g.name for g in font if "." in g.name and g.name.split(".")[0] in caps
             and not g.name.split(".")[1].startswith("sc")}
    return [n for n in font.glyphOrder if n in caps | forms]


def block(font):
    names = " ".join(f"\\{n}" for n in capitals(font))
    return "\n".join([
        BEGIN,
        f"@cpspCapitals = [{names}];",
        "",
        "lookup cpspCapitalSpacing {",
        f"    pos @cpspCapitals <{SPACE} 0 {2 * SPACE} 0>;",
        "} cpspCapitalSpacing;",
        "",
        "feature cpsp {",
        "    lookup cpspCapitalSpacing;",
        "} cpsp;",
        END,
    ])


def update(font):
    text = font.features.text or ""
    new = block(font)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: new, text, flags=re.DOTALL)
    else:
        text = text.rstrip("\n") + "\n\n" + new + "\n"
    font.features.text = text


def main(path):
    font = ufoLib2.Font.open(path)
    update(font)
    font.save()
    print(f"{path}: cpsp on {len(capitals(font))} capitals")


if __name__ == "__main__":
    main(sys.argv[1])
