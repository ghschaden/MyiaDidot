#!/usr/bin/env python3
"""Decomposed text drawn as the precomposed letters are.

    python scripts/nfd_compose.py [UFO]

HarfBuzz composes decomposed input (NFD) into a precomposed character the
font maps, so most software draws ὄ alike in either form; a shaper that does
not, or a font without the precomposed code point, places the marks by the
anchors instead, and upstream set those apart from its composites (the
polytonic accents 10-20 units off, the capitals' room before a breathing
20-96, the capital breve and macron, the adscript iota). As the ogonek
letters and the comma accents already are (ccmpSimpleGlyphComposition),
every precomposed character whose decomposed form draws differently is
composed back in ccmp, before any other lookup: the letter as drawn, in any
shaper. Not a mark made of marks (U+0344 = ̈ + ́): composed, it would
replace those two marks after every letter.

The rules are found by the test's own comparisons (tests/test_composites.py:
NFC and NFD ink, plain and as small caps (ư.sc is made of u.sc.horn, the
horn on u.sc's whole serif otherwise), the precomposed code points taken
out of cmap), repeated
until nothing differs, and written into the Regular's features.fea between
BEGIN and END markers (never hand-edit the block), with every letter with
a horn besides, whose marks above move per style; make_italic.py and
make_bold.py carry it to the other styles.
"""

import argparse
import sys
import tempfile
import unicodedata
from pathlib import Path

import ufo2ft
import ufoLib2
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

BEGIN = "# BEGIN NFD composition (generated by scripts/nfd_compose.py; do not edit)"
END = "# END NFD composition"
LOOKUP = "ccmpComposeAsDrawn"


def mismatches(font):
    """{code point: text} of characters whose NFC and NFD forms draw apart,
    as they are or as small caps."""
    from font_shaping import Shaper
    from test_composites import nfd_mismatches, smallcap_mismatches

    with tempfile.TemporaryDirectory() as tmp:
        a = Path(tmp) / "a.otf"
        ufo2ft.compileOTF(font, useProductionNames=False, optimizeCFF=0).save(a)
        t = TTFont(a)
        for table in t["cmap"].tables:
            for cp in list(table.cmap):
                if len(unicodedata.normalize("NFD", chr(cp))) > 1:
                    del table.cmap[cp]
        b = Path(tmp) / "b.otf"
        t.save(b)
        found = nfd_mismatches(TTFont(a), Shaper(a), Shaper(b))
        found.update(smallcap_mismatches(TTFont(a), Shaper(a), Shaper(b)))
    return {ord(v.split()[0]): v for v in found.values()}


def block(rules):
    lines = [BEGIN,
             f"lookup {LOOKUP} {{",
             "  lookupflag 0;"]
    lines += [f"    sub {' '.join(seq)} by {glyph};" for seq, glyph in rules]
    lines += [f"}} {LOOKUP};", "", "feature ccmp {", f"    lookup {LOOKUP};", "} ccmp;", END]
    return "\n".join(lines)


def write(font, rules):
    text = font.features.text
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        text = head + block(rules) + tail
    else:
        # before the first ccmp lookup: lookups apply in the order defined
        at = text.index("lookup ccmpSimpleGlyphComposition")
        text = text[:at] + block(rules) + "\n\n" + text[at:]
    font.features.text = text


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("ufo", nargs="?", default=str(ROOT / "sources/MyiaDidot-Regular.ufo"))
    args = ap.parse_args()
    font = ufoLib2.Font.open(args.ufo)
    cmap = {u: g.name for g in font for u in g.unicodes}
    rules = {}
    text = font.features.text
    if BEGIN in text:  # the rules there now are kept unless no longer needed below
        for line in text.split(BEGIN, 1)[1].split(END, 1)[0].splitlines():
            line = line.strip()
            if line.startswith("sub ") and " by " in line:
                seq, glyph = line[4:].rstrip(";").split(" by ")
                rules[glyph.strip()] = tuple(seq.split())
    # the horn letters, all of them: composites.py moves the marks above
    # clear of the horn by each style's own outlines (ở in the italics only),
    # which no mark anchor can follow, and this block serves every style
    for cp, name in cmap.items():
        nfd = unicodedata.normalize("NFD", chr(cp))
        if len(nfd) > 1 and "\u031b" in nfd and all(ord(c) in cmap for c in nfd):
            rules[name] = tuple(cmap[ord(c)] for c in nfd)
    for _ in range(4):
        bad = {cp: v for cp, v in mismatches(font).items()
               if not unicodedata.combining(unicodedata.normalize("NFD", chr(cp))[0])}
        if not bad:
            break
        for cp in bad:
            nfd = unicodedata.normalize("NFD", chr(cp))
            if unicodedata.combining(nfd[0]):
                # a mark made of marks (U+0344 = ̈ + ́): composed, it would
                # replace the two marks after every letter, not only here
                continue
            rules[cmap[cp]] = tuple(cmap[ord(c)] for c in nfd)
        write(font, sorted(((s, g) for g, s in rules.items()), key=lambda r: (r[0], r[1])))
        print(f"{len(bad)} characters drawn apart; {len(rules)} compositions")
    write(font, sorted(((s, g) for g, s in rules.items()), key=lambda r: (r[0], r[1])))
    bad = mismatches(font)
    font.save()
    print(f"{args.ufo}: {len(rules)} compositions, {len(bad)} characters still drawn apart"
          + (f": {' '.join(chr(c) for c in bad)}" if bad else ""))


if __name__ == "__main__":
    main()
